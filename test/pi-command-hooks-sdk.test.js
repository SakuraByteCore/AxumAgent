import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { compileExtensionPackage } from "../src/compile-bundled-extensions.js";

const modules = process.env.AXUM_INTEGRATION_NODE_MODULES || path.resolve("../../refs/axum-validation/pi-cache/node_modules");
const sdkFile = path.join(modules, "@earendil-works/pi-coding-agent/dist/index.js");
test("real SDK: command hooks block actual writes and continue once at Stop", { skip: !fs.existsSync(sdkFile), timeout: 30000 }, async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "axum-hooks-sdk-"));
  const oldDir = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = path.join(root, "agent");
  t.after(() => { if (oldDir === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = oldDir; fs.rmSync(root, { recursive: true, force: true }); });
  fs.mkdirSync(path.join(root, "hooks"));
  for (const file of ["command-hooks.ts", "hooks.ts"]) fs.copyFileSync(path.resolve("plugin/pi-companion", file), path.join(root, "hooks", file));
  compileExtensionPackage({ packageRoot: path.join(root, "hooks") });
  fs.symlinkSync(path.join(modules, "@earendil-works/pi-coding-agent/node_modules"), path.join(root, "node_modules"), process.platform === "win32" ? "junction" : "dir");
  const sdk = await import(pathToFileURL(sdkFile).href);
  const aiFile = path.join(modules, "@earendil-works/pi-coding-agent/node_modules/@earendil-works/pi-ai/dist/index.js");
  const ai = await import(pathToFileURL(fs.existsSync(aiFile) ? aiFile : path.join(modules, "@earendil-works/pi-ai/dist/index.js")).href);
  const { registerCommandHooks } = await import(pathToFileURL(path.join(root, "hooks/hooks.js")).href);
  fs.mkdirSync(process.env.PI_CODING_AGENT_DIR);
  const script = path.join(root, "check.cjs");
  fs.writeFileSync(script, `let raw='';process.stdin.on('data',d=>raw+=d);process.stdin.on('end',()=>{const input=JSON.parse(raw);if(input.hook_event_name==='PreToolUse'){console.log(JSON.stringify({hookSpecificOutput:{hookEventName:'PreToolUse',permissionDecision:'deny',permissionDecisionReason:'blocked actual write'}}));}else {console.error('verify before stopping');process.exitCode=2;}});`);
  const command = `"${process.execPath}" "${script}"`;
  fs.writeFileSync(path.join(process.env.PI_CODING_AGENT_DIR, "hooks.json"), JSON.stringify({ hooks: Object.fromEntries(["PreToolUse", "Stop"].map(event => [event, [{ hooks: [{ type: "command", command, timeout: 5 }] }]])) }));
  const settings = sdk.SettingsManager.inMemory({ compaction: { enabled: false }, retry: { enabled: false } });
  const runtime = await sdk.ModelRuntime.create({ modelsPath: null, refreshOnCreate: false });
  const model = runtime.getModels().find(item => item.provider === "openai"); assert.ok(model);
  runtime.hasConfiguredAuth = () => true;
  runtime.getAuth = async () => ({ auth: { apiKey: "local-fake-no-network" } });
  const loader = new sdk.DefaultResourceLoader({ cwd: root, agentDir: process.env.PI_CODING_AGENT_DIR, settingsManager: settings, noExtensions: true, noSkills: true, noPromptTemplates: true, noThemes: true, extensionFactories: [registerCommandHooks] });
  await loader.reload();
  const { session } = await sdk.createAgentSession({ cwd: root, agentDir: process.env.PI_CODING_AGENT_DIR, modelRuntime: runtime, model, settingsManager: settings, sessionManager: sdk.SessionManager.inMemory(root), resourceLoader: loader, tools: ["write"] });
  t.after(() => session.dispose());
  await session.bindExtensions({});
  let requests = 0;
  session.agent.streamFunction = async (m) => {
    const content = requests++ === 0 ? [{ type: "toolCall", id: "blocked-write", name: "write", arguments: { path: "denied.txt", content: "must not exist" } }] : [{ type: "text", text: "done" }];
    const message = { role: "assistant", content, api: m.api, provider: m.provider, model: m.id, stopReason: requests === 1 ? "toolUse" : "stop", usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } }, timestamp: Date.now() };
    const stream = new ai.AssistantMessageEventStream(); stream.push({ type: "done", reason: message.stopReason, message }); stream.end(message); return stream;
  };
  await session.prompt("Write the requested file, then finish.");
  assert.equal(fs.existsSync(path.join(root, "denied.txt")), false);
  assert.ok(JSON.stringify(session.agent.state.messages).includes("blocked actual write"));
  assert.ok(JSON.stringify(session.agent.state.messages).includes("verify before stopping"));
  assert.equal(requests, 3, "one tool call, one completion, one Stop continuation");
  fs.writeFileSync(script, `console.log(JSON.stringify({hookSpecificOutput:{hookEventName:'PreToolUse',updatedInput:{path:'redirected.txt',content:'validated replacement'}}}));`);
  fs.writeFileSync(path.join(process.env.PI_CODING_AGENT_DIR, "hooks.json"), JSON.stringify({ hooks: { PreToolUse: [{ hooks: [{ type: "command", command }] }] } }));
  requests = 0;
  await session.prompt("Write with hook input replacement.");
  assert.equal(fs.readFileSync(path.join(root, "redirected.txt"), "utf8"), "validated replacement");
  assert.equal(fs.existsSync(path.join(root, "denied.txt")), false);
  fs.writeFileSync(script, `console.log(JSON.stringify({hookSpecificOutput:{hookEventName:'PreToolUse',updatedInput:{path:42}}}));`);
  requests = 0;
  await session.prompt("Reject invalid replacement before the write.");
  assert.ok(JSON.stringify(session.agent.state.messages).includes("Validation failed"));

});
